  static async create(): Promise<PrismaRepository> {
    const pkg = '@prisma/client'; // resolved at runtime (generated by `prisma generate`)
    const mod: any = await import(pkg);
    const db = new mod.PrismaClient();
    await db.$connect();
    const repo = new PrismaRepository(db);
    await repo.ensureReferenceData();
    return repo;
  }

  private async ensureReferenceData() {
    const n = await this.db.pipelineStage.count();
    if (!n) {
      await this.db.pipelineStage.createMany({ data: PIPELINE_STAGES.map((s, i) => ({ key: s.key, label: s.label, order: i })), skipDuplicates: true });
    }
    const c = await this.db.productCategory.count();
    if (!c) await this.db.productCategory.createMany({ data: HARDWARE_CATEGORIES.map((name) => ({ name, isDefault: true })), skipDuplicates: true });
  }

  // ---------------------------------------------------------------- query → SQL
  private buildWhere(q: OpportunityQuery, now = new Date()): any {
    const AND: any[] = [];
    if (!q.includeMerged) AND.push({ status: { not: 'MERGED' } });
    if (!q.includeIrrelevant && !(q.intent ?? []).includes('IRRELEVANT')) AND.push({ intentLevel: { not: 'IRRELEVANT' } });
    if (q.intent?.length) AND.push({ intentLevel: { in: q.intent } });
    if (q.categories?.length) AND.push({ categories: { hasSome: expandCategories(q.categories) } });
    if (q.sourceTypes?.length) AND.push({ sourceType: { in: q.sourceTypes } });
    if (q.sourceKeys?.length) AND.push({ sourceKey: { in: q.sourceKeys } });
    if (q.states?.length) AND.push({ state: { in: q.states } });
    if (q.orgTypes?.length) AND.push({ organizationType: { in: q.orgTypes } });
    if (q.procurementTypes?.length) AND.push({ procurementType: { in: q.procurementTypes } });
    if (q.match?.length) AND.push({ matchLevel: { in: q.match } });
    if (q.status?.length) AND.push({ status: { in: q.status } });
    if (q.owner) AND.push({ owner: q.owner });
    if (q.saved) AND.push({ saved: true });
    if (q.data === 'live') AND.push({ isDemo: false });
    if (q.data === 'demo') AND.push({ isDemo: true });
    if (q.qtyMin != null) AND.push({ quantity: { gte: q.qtyMin } });
    if (q.qtyMax != null) AND.push({ quantity: { lte: q.qtyMax } });
    const disc = windowRange(q.discovered, now, q.dateFrom, q.dateTo);
    if (disc) AND.push({ discoveredAt: { gte: new Date(disc[0]), lt: new Date(disc[1]) } });
    const pub = windowRange(q.posted, now, q.dateFrom, q.dateTo);
    if (pub) AND.push({ publishedAt: { gte: new Date(pub[0]), lt: new Date(pub[1]) } });
    const dl = deadlineRange(q.deadlineWithin, now);
    if (dl) AND.push({ deadline: { gte: new Date(dl[0]), lte: new Date(dl[1]) } });
    if (q.q?.trim()) {
      for (const term of q.q.trim().split(/\s+/)) {
        const c = { contains: term, mode: 'insensitive' };
        AND.push({
          OR: [
            { title: c }, { organizationName: c }, { description: c }, { requirementSummary: c }, { aiSummary: c }, { city: c },
            { state: { equals: term.toUpperCase() } }, { source: c }, { categories: { has: term[0].toUpperCase() + term.slice(1).toLowerCase() } },
            { brandsRequested: { has: term } }, { modelsRequested: { has: term } }, { partNumbers: { has: term.toUpperCase() } },
          ],
        });
      }
    }
    return { AND };
  }

  private orderBy(sort: OpportunityQuery['sort']): any[] {
    switch (sort) {
      case 'discovered':
        return [{ discoveredAt: 'desc' }];
      case 'published':
        return [{ publishedAt: { sort: 'desc', nulls: 'last' } }];
      case 'deadline':
        return [{ deadline: { sort: 'asc', nulls: 'last' } }];
      case 'value':
        return [{ estimatedOpportunityValue: { sort: 'desc', nulls: 'last' } }];
      case 'intent':
        return [{ intentScore: 'desc' }];
      default:
        return [{ overallOpportunityScore: 'desc' }, { intentScore: 'desc' }];
    }
  }

  async listOpportunities(q: OpportunityQuery): Promise<Page<OpportunitySummary>> {
    const where = this.buildWhere(q);
    const pageSize = Math.min(Math.max(q.pageSize ?? 20, 1), 100);
    const total = await this.db.opportunity.count({ where });
    const totalPages = Math.max(1, Math.ceil(total / pageSize));
    const page = Math.min(Math.max(q.page ?? 1, 1), totalPages);
    const rows = await this.db.opportunity.findMany({ where, orderBy: this.orderBy(q.sort), skip: (page - 1) * pageSize, take: pageSize, select: SUMMARY_SELECT });
    return { items: rows.map(toSummary), total, page, pageSize, totalPages };
  }

  async exportRows(q: OpportunityQuery, limit: number) {
    const rows = await this.db.opportunity.findMany({ where: this.buildWhere(q), orderBy: this.orderBy(q.sort), take: limit, select: SUMMARY_SELECT });
    return rows.map(toSummary);
  }

