  // ---------------------------------------------------------------- settings
  async getSettings(): Promise<AppSettings> {
    const row = await this.db.appSetting.findUnique({ where: { key: 'settings' } });
    const cats = await this.db.productCategory.findMany({ orderBy: { createdAt: 'asc' } });
    const s = { ...defaultSettings(), ...(row?.value ?? {}) };
    if (cats.length) s.categories = cats.map((c: any) => c.name);
    return s;
  }
  async updateSettings(patch: Partial<AppSettings>) {
    const cur = await this.getSettings();
    const next = { ...cur, ...patch };
    await this.db.appSetting.upsert({ where: { key: 'settings' }, create: { key: 'settings', value: next }, update: { value: next } });
    if (patch.categories) await this.db.productCategory.createMany({ data: patch.categories.map((name) => ({ name })), skipDuplicates: true });
    return this.getSettings();
  }

