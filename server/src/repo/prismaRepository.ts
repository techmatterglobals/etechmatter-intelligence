  // ---------------------------------------------------------------- historical
  async upsertHistorical(records: HistoricalRecord[]) {
    let added = 0;
    for (const r of records) {
      const exists = await this.db.historicalAward.findUnique({ where: { sourceKey_awardId: { sourceKey: r.sourceKey, awardId: r.awardId } }, select: { id: true } });
      const data = { ...r, retrievedAt: date(r.retrievedAt)! };
      if (exists) {
        const { id: _id, ...upd } = data;
        await this.db.historicalAward.update({ where: { id: exists.id }, data: upd });
      } else {
        await this.db.historicalAward.create({ data });
        added++;
      }
    }
    return added;
  }
  async listHistorical(limit: number) {
    const rows = await this.db.historicalAward.findMany({ orderBy: { actionDate: 'desc' }, take: limit });
    return rows.map((r: any) => ({ ...r, retrievedAt: iso(r.retrievedAt)! }));
  }
