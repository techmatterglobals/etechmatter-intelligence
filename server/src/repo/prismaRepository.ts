  private src(r: any): SourceConfigRecord {
    return { key: r.key, enabled: r.enabled, intervalMinutes: r.intervalMinutes, config: r.config ?? {}, lastRunAt: iso(r.lastRunAt), lastSuccessAt: iso(r.lastSuccessAt), lastRunNew: r.lastRunNew, lastStatus: r.lastStatus, lastMessage: r.lastMessage };
  }
  async getSourceConfigs() {
    return (await this.db.source.findMany()).map((r: any) => this.src(r));
  }
  async upsertSourceConfig(key: string, patch: Partial<SourceConfigRecord>) {
    const data: any = {};
    for (const [k, v] of Object.entries(patch)) {
      if (k === 'key') continue;
      data[k] = k === 'lastRunAt' || k === 'lastSuccessAt' ? date(v as string | null) : v;
    }
    const r = await this.db.source.upsert({ where: { key }, create: { key, ...data }, update: data });
    return this.src(r);
  }
