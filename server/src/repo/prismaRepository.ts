  async saveOpportunity(o: Opportunity) {
    const orgKey = organizationKey(o.organizationName);
    await this.db.$transaction(async (tx: any) => {
      let organizationId: string | null = null;
      if (orgKey && o.organizationName) {
        const org = await tx.organization.upsert({
          where: { key: orgKey },
          create: { key: orgKey, name: o.organizationName, type: o.organizationType, website: o.organizationWebsite, industry: o.industry, city: o.city, state: o.state, isDemo: o.isDemo },
          update: { website: o.organizationWebsite ?? undefined, city: o.city ?? undefined, state: o.state ?? undefined },
        });
        organizationId = org.id;
      }
      const data = { ...this.scalars(o), organizationId };
      await tx.opportunity.upsert({ where: { id: o.id }, create: { id: o.id, ...data }, update: data });

      // normalized child tables (replaced on every analysis)
      await tx.opportunityEvidence.deleteMany({ where: { opportunityId: o.id } });
      if (o.evidence.length)
        await tx.opportunityEvidence.createMany({
          data: o.evidence.map((e) => ({ id: e.id, opportunityId: o.id, sourceUrl: e.sourceUrl, sourceName: e.sourceName, snippet: e.snippet, field: e.field, publishedAt: date(e.publishedAt), retrievedAt: date(e.retrievedAt)! })),
          skipDuplicates: true,
        });
      await tx.opportunityScore.deleteMany({ where: { opportunityId: o.id } });
      if (o.scoreReasons.length) await tx.opportunityScore.createMany({ data: o.scoreReasons.map((s) => ({ opportunityId: o.id, code: s.code, label: s.label, points: s.points })) });
      await tx.opportunityProduct.deleteMany({ where: { opportunityId: o.id } });
      const pm = o.productMatches.filter((m) => m.level !== 'NONE');
      if (pm.length) {
        const existing = await tx.product.findMany({ where: { id: { in: pm.map((m) => m.productId) } }, select: { id: true } });
        const ok = new Set(existing.map((p: any) => p.id));
        const rows = pm.filter((m) => ok.has(m.productId)).map((m) => ({ opportunityId: o.id, productId: m.productId, level: m.level, score: m.score, requestedItem: m.requestedItem, reason: m.reason }));
        if (rows.length) await tx.opportunityProduct.createMany({ data: rows });
      }
// Rebuild opportunity-contact associations from the current analysis.
// Preserve shared Contact records used by other opportunities.
await tx.opportunityContact.deleteMany({
  where: { opportunityId: o.id },
});
      // contacts (only publicly stated ones ever reach here)
      for (const c of o.contacts) {
        if (!c.email && !c.phone && !c.name) continue;
        const found = c.email ? await tx.contact.findFirst({ where: { email: c.email, organizationId } }) : null;
        const contact = found ?? (await tx.contact.create({ data: { name: c.name, title: c.title, email: c.email, phone: c.phone, linkedin: c.linkedin, provenance: c.provenance, organizationId } }));
        await tx.opportunityContact.upsert({
          where: { opportunityId_contactId: { opportunityId: o.id, contactId: contact.id } },
          create: { opportunityId: o.id, contactId: contact.id, role: c.role, isPrimary: c.email === o.buyerEmail && !!c.email },
          update: { role: c.role },
        });
      }
      await tx.aIAnalysis.create({ data: { opportunityId: o.id, provider: o.aiProvider, documentKind: o.documentKind, summary: o.aiSummary, reasoning: o.aiReasoning } });
      for (const n of o.notes) await tx.note.upsert({ where: { id: n.id }, create: { id: n.id, opportunityId: o.id, author: n.author, body: n.body, createdAt: date(n.createdAt)! }, update: {} });
      for (const a of o.activities)
        await tx.salesActivity.upsert({ where: { id: a.id }, create: { id: a.id, opportunityId: o.id, type: a.type, actor: a.actor, detail: a.detail, createdAt: date(a.createdAt)! }, update: {} });
    }, { timeout: 30_000 });
    return (await this.getOpportunity(o.id))!;
  }

  async patchOpportunity(id: string, patch: Partial<Opportunity>) {
    const cur = await this.getOpportunity(id);
    if (!cur) return null;
    const next = { ...cur, ...patch };
    const data: any = {};
    const s = this.scalars(next);
    for (const k of Object.keys(patch)) {
      if (k === 'notes' || k === 'activities' || k === 'evidence') continue;
      const map: Record<string, string> = { duplicateCandidates: 'duplicateCandidates', contacts: 'contactsJson', scoreReasons: 'scoreReasonsJson', productMatches: 'productMatchesJson' };
      const col = map[k] ?? k;
      if (col in s) data[col] = (s as any)[col];
      if (k === 'duplicateCandidates') data.hasDuplicates = next.duplicateCandidates.length > 0;
    }
    await this.db.$transaction(async (tx: any) => {
      if (Object.keys(data).length) await tx.opportunity.update({ where: { id }, data });
      if (patch.notes) for (const n of patch.notes) await tx.note.upsert({ where: { id: n.id }, create: { id: n.id, opportunityId: id, author: n.author, body: n.body, createdAt: date(n.createdAt)! }, update: {} });
      if (patch.activities)
        for (const a of patch.activities) await tx.salesActivity.upsert({ where: { id: a.id }, create: { id: a.id, opportunityId: id, type: a.type, actor: a.actor, detail: a.detail, createdAt: date(a.createdAt)! }, update: {} });
    });
    return this.getOpportunity(id);
  }

